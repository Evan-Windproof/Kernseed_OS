"""Generate mechanical vector stubs, not C handlers. Intel/AMD error-code set.
21=#CP, 29=#VC and 30=#SX matter on CPUs exposing those features too.
Never use software INT to test an error-code exception: INT pushes no error.
"""
import sys
from pathlib import Path
error_vectors = {8, 10, 11, 12, 13, 14, 17, 21, 29, 30}
lines = ['/* Generated by scripts/gen-isr.py; do not edit. */', '.section .text']
for vector in range(256):
    lines += [f'.global isr_{vector}', f'.type isr_{vector}, @function', f'isr_{vector}:']
    if vector not in error_vectors:
        lines += ['    pushq $0']
    lines += [f'    pushq ${vector}', '    jmp isr_common', f'.size isr_{vector}, .-isr_{vector}']
lines += ['.section .rodata', '.balign 8', '.global isr_table', 'isr_table:']
lines += [f'    .quad isr_{vector}' for vector in range(256)]
lines += ['.section .note.GNU-stack,"",@progbits', '']
Path(sys.argv[1]).write_text('\n'.join(lines))
